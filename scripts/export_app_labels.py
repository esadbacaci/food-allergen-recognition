# -*- coding: utf-8 -*-
"""Generate the web application's label files from data/class_map_v2.csv (single source of truth).

    python scripts/export_app_labels.py <path to calorieapp checkout>

Writes  <app>/ml/model_labels.txt        206 class ids in model output order
        <app>/Services/FoodNameTranslator.cs   dictionary block regenerated (TR/EN display names)
Turkish names of Food-101 classes are taken from the existing translator; the four Food-101
classes restored in v2 get the names below.
"""
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from foodallergen import paths  # noqa: E402

NEW_TR = {"omelette": "Omlet", "mussels": "Midye (buğulama)", "baby-back-ribs": "Domuz kaburga",
          "pulled-pork-sandwich": "Didiklenmiş domuz eti sandviç"}
BEGIN = "    private static readonly Dictionary<string, (string Tr, string En)> _translations"


def main(app):
    app = Path(app)
    rows = sorted(csv.DictReader(open(paths.CLASS_MAP_V2, encoding="utf-8")), key=lambda r: int(r["index"]))
    (app / "ml" / "model_labels.txt").write_text(
        "# One class label per line, in model output order (generated from 02_kod/data/class_map_v2.csv).\n"
        + "\n".join(r["class_id"] for r in rows) + "\n", encoding="utf-8")

    cs = (app / "Services" / "FoodNameTranslator.cs").read_text(encoding="utf-8-sig")
    entry = re.compile(r'\{\s*"([^"]+)",\s*\((?:Tr:\s*)?"([^"]*)",\s*(?:En:\s*)?"[^"]*"\)\s*\}')
    old_tr = {m.group(1): m.group(2) for m in entry.finditer(cs)}
    if len(old_tr) < 150:
        sys.exit(f"only {len(old_tr)} existing translations parsed - refusing to overwrite the translator")
    start = cs.index(BEGIN)
    end = cs.index("};", start) + 2
    lines = [BEGIN + " = new(StringComparer.OrdinalIgnoreCase)", "    {",
             "        // generated by 02_kod/scripts/export_app_labels.py from class_map_v2.csv"]
    missing = []
    for r in rows:
        c, en = r["class_id"], r["display_en"]
        tr = r["display_tr"] or NEW_TR.get(c) or old_tr.get(c)
        if not tr:
            missing.append(c)
            tr = en
        lines.append(f'        {{ "{c}", (Tr: "{tr}", En: "{en}") }},')
    lines.append("    };")
    (app / "Services" / "FoodNameTranslator.cs").write_text(cs[:start] + "\n".join(lines) + cs[end:],
                                                            encoding="utf-8")
    print(f"{len(rows)} labels written; Turkish name missing (English used): {missing}")


if __name__ == "__main__":
    main(sys.argv[1])
